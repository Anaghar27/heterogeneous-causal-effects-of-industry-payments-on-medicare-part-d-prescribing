md = []


def save(fig, name, alt):
    FIG.mkdir(parents=True, exist_ok=True)
    fig.savefig(FIG / f"{name}.png", dpi=160, bbox_inches="tight")
    plt.close(fig)
    md.append(f"\n![{alt}](figures/{name}.png)\n")


def table(df, floatfmt=2):
    md.append(df.round(floatfmt).to_markdown() + "\n")


def subtitle(ax, text):
    ax.text(0, 1.02, text, transform=ax.transAxes, color=INK2, fontsize=9, va="bottom")


def pct_axis(ax, axis="y"):
    fmt = matplotlib.ticker.PercentFormatter(1.0, decimals=0)
    (ax.yaxis if axis == "y" else ax.xaxis).set_major_formatter(fmt)


def design(m):
    X = m[NUM + FLAGS + CAT].copy()
    for c in NUM:
        X[c] = X[c].fillna(X[c].median())
    for c in FLAGS:
        X[c] = X[c].astype(float)
    return X


def smd(x, t, w=None):
    w = np.ones(len(x)) if w is None else w
    m1, m0 = np.average(x[t], weights=w[t]), np.average(x[~t], weights=w[~t])
    v1 = np.average((x[t] - m1) ** 2, weights=w[t])
    v0 = np.average((x[~t] - m0) ** 2, weights=w[~t])
    return (m1 - m0) / np.sqrt((v1 + v0) / 2)


def main():
    m = pd.read_parquet(PROCESSED / "model_2023_2024.parquet")
    flow = json.loads((LOGS / "clean_features.json").read_text())["flow"]
    t = m["treated"].to_numpy()
    md.extend(["# EDA: industry payments 2023 -> Part D brand prescribing 2024", "",
               "Aggregates only; generated by `scripts/08_eda.py` from `data/processed/model_2023_2024.parquet`.", ""])

    # ---- 0. sample flow
    md.append("## 1. Sample\n")
    f = pd.DataFrame(flow).drop(columns=["specialties"], errors="ignore").set_index("step")
    table(f, 1)
    md.append(f"Final: **{len(m):,} prescribers**, {t.mean():.1%} paid in 2023, {m['specialty'].nunique()} specialty "
              f"groups, {m['new_in_2024'].mean():.1%} new in 2024, {m['low_volume'].mean():.1%} low-volume "
              f"(<50 claims), {m['is_dentist'].mean():.1%} dentists.\n")

    # ---- 1. missingness
    md.append("## 2. Missingness\n")
    miss = (m.isna().mean() * 100).loc[lambda s: s > 0].sort_values(ascending=False).to_frame("% missing")
    miss["why"] = miss.index.map(lambda c: "suppressed (<11) by CMS" if c.startswith("x22_share") or c == "x22_opioid_rate"
                                 else "not in Part D 2022" if "22" in c or c == "y_change_brand_share"
                                 else "brand cost suppressed" if c.startswith("Brnd_Tot_Drug") else "")
    table(miss, 1)
    md.append("Brand claim counts are never missing (bounded, `brnd_imputed`); "
              f"{m['brnd_imputed'].mean():.1%} of 2024 outcomes use the bound midpoint "
              f"({m.loc[t, 'brnd_imputed'].mean():.1%} paid vs {m.loc[~t, 'brnd_imputed'].mean():.1%} unpaid).\n")

    # ---- 2. payments
    md.append("## 3. Treatment: payments in 2023\n")
    paid = m[t]
    fig, ax = plt.subplots(figsize=(7, 3.6))
    bins = np.arange(0, 6.01, 0.1)
    ax.hist(np.log10(paid["pay_usd"]), bins=bins, color=PAID, rwidth=0.85)
    ax.set_xticks(range(0, 7), ["$1", "$10", "$100", "$1k", "$10k", "$100k", "$1M"])
    ax.set_xlabel("total 2023 payments per prescriber (log scale)")
    ax.set_ylabel("prescribers")
    ax.yaxis.set_major_formatter(matplotlib.ticker.FuncFormatter(lambda v, _: f"{v / 1000:.0f}K" if v else "0"))
    ax.set_title(f"Half of paid prescribers received under ${paid['pay_usd'].median():,.0f} in 2023", pad=18)
    subtitle(ax, f"{len(paid):,} paid prescribers; median ${paid['pay_usd'].median():,.0f}")
    save(fig, "01_payment_amounts", "Histogram of total payment per paid prescriber, log scale")
    q = paid["pay_usd"].quantile([0.1, 0.25, 0.5, 0.75, 0.9, 0.99]).to_frame("USD")
    q.index = [f"p{int(100 * i)}" for i in q.index]
    table(q.T, 0)
    g = m.groupby("pay_group", observed=True).agg(prescribers=("NPI", "size"), share=("NPI", lambda s: len(s) / len(m)),
                                                  pct_food_only=("pay_food_only", "mean"))
    g["share"] *= 100
    g["pct_food_only"] *= 100
    table(g, 1)

    usd_cols = [c for c in m.columns if c.startswith("usd_")]
    nat = paid[usd_cols].sum().sort_values()
    nat.index = nat.index.str.replace("usd_", "")
    fig, ax = plt.subplots(figsize=(7, 3.2))
    ax.barh(nat.index, nat / 1e6, color=PAID, height=0.6)
    for i, v in enumerate(nat / 1e6):
        ax.text(v, i, f"  ${v:,.0f}M", va="center", color=INK2, fontsize=9)
    ax.set_xlabel("2023 payment dollars to prescribers in the cohort ($M)")
    ax.grid(axis="y", visible=False)
    ax.set_title("Royalties, speaking and consulting carry the dollars; food carries the counts", pad=18)
    subtitle(ax, f"total ${nat.sum() / 1e6:,.0f}M; {paid['pay_food_only'].mean():.0%} of paid prescribers got food only")
    ax.set_xlim(0, nat.max() / 1e6 * 1.2)
    save(fig, "02_payment_types", "Payment dollars by nature of payment")
    table((nat / 1e6).to_frame("USD millions").sort_values("USD millions", ascending=False), 1)

    # ---- 3. outcome
    md.append("## 4. Outcome: brand share of claims, 2024\n")
    fig, ax = plt.subplots(figsize=(7, 3.6))
    b = np.linspace(0, 1, 51)
    for mask, col, lab in [(~t, UNPAID, "unpaid"), (t, PAID, "paid")]:
        ax.hist(m.loc[mask, "y_brand_share"], bins=b, histtype="step", color=col, linewidth=2, density=True, label=lab)
    pct_axis(ax, "x")
    ax.set_xlabel("brand-name share of prescriptions, 2024 (bound midpoint)")
    ax.set_ylabel("density")
    ax.legend(loc="upper right")
    ax.set_title("Brand share is right-skewed; most prescribers sit under 20%", pad=18)
    subtitle(ax, "unadjusted; dentists and orthopedics pile up near 0%")
    save(fig, "03_outcome_distribution", "Distribution of 2024 brand share, paid vs unpaid")
    out = m.groupby("treated").agg(n=("NPI", "size"), mean_share=("y_brand_share", "mean"),
                                   median_share=("y_brand_share", "median"),
                                   pooled_share=("Brnd_Tot_Clms_mid", "sum"), clms=("Tot_Clms", "sum"),
                                   mean_change_22_24=("y_change_brand_share", "mean"))
    out["pooled_share"] = out["pooled_share"] / out.pop("clms")
    out.index = out.index.map({False: "unpaid", True: "paid"})
    table(out, 4)
    unf = m["y_share_uninformative"]
    wb = m.groupby("treated")["y_share_uninformative"].mean().rename(index={False: "unpaid", True: "paid"}) * 100
    md.append(f"**Bound width.** For {unf.mean():.1%} of prescribers the 2024 brand-share bounds are wider than 10 points "
              f"(paid {wb['paid']:.1f}%, unpaid {wb['unpaid']:.1f}%); almost all are tiny prescribers (11-50 claims) where "
              "CMS suppressed nearly every cell, so the midpoint is a guess (this is the spike at exactly 50% above). "
              "Flag: `y_share_uninformative`.\n")
    bw = m.groupby(pd.cut(m["Tot_Clms"], [10, 20, 50, 100, 500, np.inf]), observed=True).agg(
        prescribers=("NPI", "size"), median_bound_width_pts=("y_share_bound_width", "median"),
        pct_uninformative=("y_share_uninformative", "mean"))
    bw["median_bound_width_pts"] *= 100
    bw["pct_uninformative"] *= 100
    bw.index = bw.index.astype(str).rename("2024 total claims")
    table(bw, 1)
    md.append(f"Unadjusted, paid prescribers have a higher brand share (mean {out.loc['paid', 'mean_share']:.1%} vs "
              f"{out.loc['unpaid', 'mean_share']:.1%}; claims-weighted {out.loc['paid', 'pooled_share']:.1%} vs "
              f"{out.loc['unpaid', 'pooled_share']:.1%}), but they already differed before payment (2022 brand share, "
              "size, specialty; section 6), so this gap is confounded, not causal.\n")

    # ---- 4. who gets paid
    md.append("## 5. Who gets paid\n")
    s = m.groupby("specialty").agg(n=("NPI", "size"), pct_paid=("treated", "mean")).sort_values("n", ascending=False).head(20)
    s = s.sort_values("pct_paid")
    s.index = s.index.map(lambda k: LABEL.get(k, k))
    fig, ax = plt.subplots(figsize=(7, 6))
    ax.barh(s.index, s["pct_paid"], color=PAID, height=0.6)
    for i, v in enumerate(s["pct_paid"]):
        ax.text(v, i, f" {v:.0%}", va="center", color=INK2, fontsize=8)
    pct_axis(ax, "x")
    ax.set_xlim(0, 1.05)
    ax.grid(axis="y", visible=False)
    ax.tick_params(axis="y", labelsize=8, colors=INK2)
    ax.set_title("Share paid in 2023, 20 largest specialties", pad=18)
    subtitle(ax, "treatment varies strongly by specialty: specialty must be adjusted for")
    save(fig, "04_paid_by_specialty", "Share of prescribers paid in 2023 by specialty")
    table(s.sort_values("n", ascending=False).assign(pct_paid=lambda d: 100 * d["pct_paid"]), 1)
    r = m.groupby("region").agg(n=("NPI", "size"), pct_paid=("treated", "mean"))
    r["pct_paid"] *= 100
    u = m.groupby("ruca_group").agg(n=("NPI", "size"), pct_paid=("treated", "mean"))
    u["pct_paid"] *= 100
    table(r, 1)
    table(u, 1)

    # ---- 5. propensity, overlap, balance
    md.append("## 6. Confounding, balance and overlap\n")
    X = design(m)
    pre = ColumnTransformer([("num", StandardScaler(), NUM + FLAGS),
                             ("cat", OneHotEncoder(handle_unknown="ignore", min_frequency=50), CAT)])
    model = make_pipeline(pre, LogisticRegression(max_iter=1000, C=1.0))
    rng = np.random.default_rng(0)
    fit_idx = rng.choice(len(m), size=min(400_000, len(m)), replace=False)
    model.fit(X.iloc[fit_idx], t[fit_idx])
    ps = model.predict_proba(X)[:, 1]
    hold = np.setdiff1d(np.arange(len(m)), fit_idx)
    auc = roc_auc_score(t[hold], ps[hold])

    fig, ax = plt.subplots(figsize=(7, 3.6))
    b = np.linspace(0, 1, 51)
    for mask, col, lab in [(~t, UNPAID, "unpaid"), (t, PAID, "paid")]:
        ax.hist(ps[mask], bins=b, histtype="step", color=col, linewidth=2, density=True, label=lab)
    ax.set_xlabel("estimated probability of being paid (propensity score)")
    ax.set_ylabel("density")
    ax.legend(loc="upper left")
    ax.set_title("Paid and unpaid prescribers overlap across most of the range", pad=18)
    subtitle(ax, f"logistic model on 2022 covariates + specialty, region, RUCA; held-out AUC {auc:.2f}")
    save(fig, "05_propensity_overlap", "Propensity score distributions for paid and unpaid prescribers")
    extreme = {"ps < 0.05": float((ps < 0.05).mean()), "ps > 0.95": float((ps > 0.95).mean())}
    ov = pd.DataFrame({
        "paid": [np.mean(ps[t] < 0.05), np.mean(ps[t] > 0.95), np.median(ps[t])],
        "unpaid": [np.mean(ps[~t] < 0.05), np.mean(ps[~t] > 0.95), np.median(ps[~t])],
    }, index=["share ps < 0.05", "share ps > 0.95", "median ps"])
    table(ov, 3)

    psc = np.clip(ps, 0.01, 0.99)
    w = np.where(t, 1 / psc, 1 / (1 - psc))
    rows = []
    for c in NUM + ["new_in_2024"]:
        x = X[c].to_numpy(float)
        rows.append({"covariate": LABEL[c], "unadjusted": smd(x, t), "IPW-weighted": smd(x, t, w)})
    for sp in m["specialty"].value_counts().head(8).index:
        x = (m["specialty"] == sp).to_numpy(float)
        rows.append({"covariate": f"specialty: {LABEL.get(sp, sp)}", "unadjusted": smd(x, t), "IPW-weighted": smd(x, t, w)})
    bal = pd.DataFrame(rows).set_index("covariate")
    bal = bal.reindex(bal["unadjusted"].abs().sort_values().index)
    fig, ax = plt.subplots(figsize=(7, 6))
    y = np.arange(len(bal))
    ax.axvspan(-0.1, 0.1, color=GRID, alpha=0.6, linewidth=0)
    ax.axvline(0, color=AXIS, linewidth=0.8)
    ax.scatter(bal["unadjusted"], y, s=40, color=UNPAID, edgecolor=SURFACE, linewidth=1.5, zorder=3, label="unadjusted")
    ax.scatter(bal["IPW-weighted"], y, s=40, color=PAID, edgecolor=SURFACE, linewidth=1.5, zorder=3, label="IPW-weighted")
    ax.set_yticks(y, bal.index, fontsize=8, color=INK2)
    ax.grid(axis="y", visible=False)
    ax.set_xlabel("standardized mean difference (paid - unpaid)")
    ax.legend(loc="lower right")
    ax.set_title("Paid prescribers are bigger and different; weighting balances them", pad=18)
    subtitle(ax, "shaded band = |SMD| < 0.1, the usual balance threshold")
    save(fig, "06_covariate_balance", "Standardized mean differences before and after propensity weighting")
    table(bal, 3)
    md.append(f"Propensity model held-out AUC = {auc:.3f}. Max |SMD| unadjusted {bal['unadjusted'].abs().max():.2f}, "
              f"after IPW {bal['IPW-weighted'].abs().max():.2f}. Share of all prescribers with ps<0.05: "
              f"{extreme['ps < 0.05']:.1%}, ps>0.95: {extreme['ps > 0.95']:.1%}.\n")

    # ---- 6. trends by payment history
    md.append("## 7. Brand share over time by payment history\n")
    p23 = pd.read_parquet(PROCESSED / "partd_by_provider_2023.parquet", columns=["NPI", "brand_share_mid"])
    h = m[~m["new_in_2024"]].merge(p23.rename(columns={"brand_share_mid": "s23"}), on="NPI", how="inner")
    h["history"] = np.select(
        [~h["paid_2022"] & ~h["treated"], ~h["paid_2022"] & h["treated"], h["paid_2022"] & h["treated"]],
        ["never paid", "newly paid 2023", "paid 2022 and 2023"], "paid 2022 only")
    tr = h.groupby("history").agg(n=("NPI", "size"), y2022=("x_brand_share_22", "mean"), y2023=("s23", "mean"),
                                  y2024=("y_brand_share", "mean"))
    order = ["never paid", "newly paid 2023", "paid 2022 and 2023", "paid 2022 only"]
    tr = tr.loc[order]
    colors = {"never paid": UNPAID, "newly paid 2023": PAID, "paid 2022 and 2023": AQUA, "paid 2022 only": YELLOW}
    fig, ax = plt.subplots(figsize=(7, 4))
    yrs = [2022, 2023, 2024]
    ends = {}
    for k in order:
        v = 100 * (tr.loc[k, ["y2022", "y2023", "y2024"]].to_numpy(float) - tr.loc[k, "y2022"])
        ax.plot(yrs, v, color=colors[k], marker="o", markersize=6, markeredgecolor=SURFACE, markeredgewidth=1.5,
                label=k)
        ends[k] = v[-1]
    # end labels with leader lines, spread so they never overlap
    lo_y, hi_y = ax.get_ylim()
    gap = (hi_y - lo_y) * 0.09
    placed = []
    for k, v in sorted(ends.items(), key=lambda kv: kv[1]):
        y = max(v, placed[-1] + gap) if placed else v
        placed.append(y)
        ax.plot([2024.04, 2024.16], [v, y], color=AXIS, linewidth=0.8)
        ax.text(2024.19, y, f"{k}  {v:+.2f}", va="center", color=INK2, fontsize=8)
    ax.axhline(0, color=AXIS, linewidth=0.8)
    ax.axvspan(2022.5, 2023.5, color=GRID, alpha=0.5, linewidth=0)
    ax.set_xticks(yrs, [str(x) for x in yrs])
    ax.set_xlim(2021.85, 2025.0)
    ax.set_ylabel("change in mean brand share since 2022 (points)", fontsize=9)
    ax.legend(loc="upper center", bbox_to_anchor=(0.45, -0.1), ncol=4, fontsize=8, handlelength=1.5)
    ax.set_title("Only the newly paid group's brand share rose after 2022", pad=18)
    subtitle(ax, "unadjusted, prescribers present 2022-2024; shaded = 2023 payment year")
    save(fig, "07_trends_by_history", "Mean brand share 2022 to 2024 by payment history group")
    tr2 = tr.copy()
    tr2[["y2022", "y2023", "y2024"]] *= 100
    tr2["change_22_24_pts"] = tr2["y2024"] - tr2["y2022"]
    table(tr2, 2)

    # ---- 7. dose response (adjusted, from step 6 screen)
    md.append("## 8. Dose-response (adjusted screen from `06_low_payment_check.py`)\n")
    est = pd.DataFrame(json.loads((LOGS / "low_payment_check.json").read_text())["estimates"])
    e = est[est["bounds"] == "mid"].set_index("group")
    lab = {"usd_1_25": "$1-25", "usd_25_100": "$25-100", "usd_100_1k": "$100-1k", "usd_gt_1k": ">$1k"}
    e.index = e.index.map(lab)
    fig, ax = plt.subplots(figsize=(7, 3.6))
    x = np.arange(len(e))
    ax.bar(x, e["effect_pts"], color=PAID, width=0.5)
    ax.errorbar(x, e["effect_pts"], yerr=[e["effect_pts"] - e["ci_lo"], e["ci_hi"] - e["effect_pts"]],
                fmt="none", ecolor=INK2, elinewidth=1.2, capsize=4)
    for xi, v in zip(x, e["effect_pts"]):
        ax.text(xi + 0.28, v, f"+{v:.2f}", ha="left", va="center", color=INK2, fontsize=9)
    ax.set_xticks(x, e.index)
    ax.axhline(0, color=AXIS, linewidth=0.8)
    ax.grid(axis="x", visible=False)
    ax.set_ylabel("extra change in brand share\n2022->2024 (points)")
    ax.set_xlabel("newly paid in 2023, by amount (vs never paid)")
    ax.set_ylim(0, (e["ci_hi"].max()) * 1.15)
    ax.set_title("Larger payments, larger rise in brand prescribing", pad=18)
    subtitle(ax, "adjusted for specialty, state, RUCA and 2022 covariates; 95% CI")
    save(fig, "08_dose_response", "Adjusted change in brand share by payment amount")
    piv = est.pivot(index="group", columns="bounds", values="effect_pts").loc[list(lab)][["lo", "mid", "hi"]]
    piv.index = piv.index.map(lab)
    table(piv, 3)

    # ---- key takeaways
    md.append("## Takeaways for modeling\n")
    md.extend([
        f"- Treatment is common ({t.mean():.0%}) and mostly small: median ${paid['pay_usd'].median():,.0f}; "
        f"{paid['pay_food_only'].mean():.0%} of paid prescribers got food only. Model dose (`pay_log1p_usd`, `pay_group`) "
        "alongside the binary treatment.",
        "- Strong confounding: paid prescribers are larger (SMD ~0.45 on claims/beneficiaries), had higher 2022 brand "
        "share, and differ by specialty. Weighting on 2022 covariates balances them (all |SMD| < 0.1).",
        "- Royalties/licenses are the largest dollar category but reward device inventors, not prescribing; consider "
        "excluding `usd_royalty` from dose measures.",
        f"- Overlap is adequate (AUC {auc:.2f}); trim or clip extreme propensities before IPW/DR estimation.",
        "- Use the 2022 baseline: prescribers new in 2024 (16%) lack it; analyze them separately or impute with a flag.",
        "- Suppression: patient-mix covariates are 35-52% missing; keep missing-indicators. Report outcome results at "
        "low/mid/high bounds.",
        "- Restrict the share outcome to prescribers with informative bounds (`~y_share_uninformative`), or use brand "
        "claim counts; the midpoint share is unreliable for tiny prescribers (spike at 50%).",
        "- Dentists (~10%) and low-volume prescribers (~27%) have near-zero, noisy brand shares; run sensitivity "
        "analyses excluding them.",
    ])
    REPORT.parent.mkdir(parents=True, exist_ok=True)
    REPORT.write_text("\n".join(md) + "\n", encoding="utf-8")
    print("\n".join(md))


if __name__ == "__main__":
    main()
